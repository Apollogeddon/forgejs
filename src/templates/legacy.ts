// Line endings, trailing spaces and blank lines don't make a file the project's own
function normaliseWorkflow(content: string): string {
  return content
    .replace(/\r\n/g, "\n")
    .split("\n")
    .map((line) => line.trimEnd())
    .filter((line) => line.trim() !== "")
    .join("\n");
}

export function isLegacyWorkflow(file: string, content: string): boolean {
  const hash = createHash("sha256").update(normaliseWorkflow(content)).digest("hex");
  return LEGACY_WORKFLOWS[file]?.has(hash) ?? false;
}
